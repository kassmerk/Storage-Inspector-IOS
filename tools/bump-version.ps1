# Version bump for the .ipa builds: one command instead of editing project.pbxproj by hand.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\bump-version.ps1
#       build number +1, marketing version untouched           1.1 (4) -> 1.1 (5)
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\bump-version.ps1 -Version 1.2
#       marketing version 1.2, build number +1                 1.1 (4) -> 1.2 (5)
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\bump-version.ps1 -Version 1.2 -Build 1
#       exactly 1.2 (1) - use this when the build number has to restart
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\bump-version.ps1 -DryRun
#       show what would change, write nothing
#
# Both settings live in project.pbxproj twice (Debug and Release of the app target); this script
# keeps the copies in sync. Info.plist is generated by Xcode (GENERATE_INFOPLIST_FILE = YES), so
# these build settings are the only place the version is stored - About reads them at runtime.
param(
    [string]$Version,
    [int]$Build = 0,
    [string]$Project = (Join-Path $PSScriptRoot '..\StorageInspector.xcodeproj\project.pbxproj'),
    [switch]$DryRun,
    [switch]$SkipChecks
)

$ErrorActionPreference = 'Stop'

$path = (Resolve-Path -LiteralPath $Project).Path
$text = [System.IO.File]::ReadAllText($path)

$versionMatch = [regex]::Match($text, 'MARKETING_VERSION = ([^;]+);')
$buildMatch = [regex]::Match($text, 'CURRENT_PROJECT_VERSION = ([^;]+);')
if (-not $versionMatch.Success -or -not $buildMatch.Success) {
    Write-Host 'ERROR: MARKETING_VERSION / CURRENT_PROJECT_VERSION not found - wrong project.pbxproj?'
    exit 1
}

$oldVersion = $versionMatch.Groups[1].Value
$oldBuild = [int]$buildMatch.Groups[1].Value

if ([string]::IsNullOrWhiteSpace($Version)) {
    $newVersion = $oldVersion
} else {
    $newVersion = $Version.Trim()
    if ($newVersion -notmatch '^\d+(\.\d+){0,2}$') {
        Write-Host ("ERROR: '{0}' is not a version like 1.2 or 1.2.3" -f $Version)
        exit 1
    }
}

$newBuild = if ($Build -gt 0) { $Build } else { $oldBuild + 1 }

$newText = [regex]::Replace($text, 'MARKETING_VERSION = [^;]+;', 'MARKETING_VERSION = ' + $newVersion + ';')
$newText = [regex]::Replace($newText, 'CURRENT_PROJECT_VERSION = [^;]+;', 'CURRENT_PROJECT_VERSION = ' + $newBuild + ';')

$versionCount = ([regex]::Matches($newText, 'MARKETING_VERSION = ' + [regex]::Escape($newVersion) + ';')).Count
$buildCount = ([regex]::Matches($newText, 'CURRENT_PROJECT_VERSION = ' + $newBuild + ';')).Count

Write-Host ("Marketing version: {0} -> {1}" -f $oldVersion, $newVersion)
Write-Host ("Build number:      {0} -> {1}" -f $oldBuild, $newBuild)
Write-Host ("project.pbxproj:   version found {0}x, build found {1}x (expected 2 each)" -f $versionCount, $buildCount)

if ($versionCount -ne 2 -or $buildCount -ne 2) {
    Write-Host 'ERROR: the settings are not in both configurations - nothing written.'
    exit 1
}

if ($DryRun) {
    Write-Host 'Dry run: project.pbxproj not modified.'
    exit 0
}

# WriteAllText keeps the file byte-exact apart from those two numbers: no BOM is added and the LF
# line endings survive, which is what check-eol.ps1 and the macOS build both rely on.
[System.IO.File]::WriteAllText($path, $newText, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("Updated {0}" -f $path)

if ($SkipChecks) { exit 0 }

Write-Host ''
& (Join-Path $PSScriptRoot 'check-pbxproj.ps1') -Project $path
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
& (Join-Path $PSScriptRoot 'check-eol.ps1') -Root (Split-Path -Parent $PSScriptRoot)
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
